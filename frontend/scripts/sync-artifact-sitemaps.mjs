// ビルド直前に artifact-sitemaps.generated.ts の読み込み口を、実在する成果物だけに絞る。
//
// 成果物のフォルダ (src/app/artifacts/<slug>/) は .gitignore で GitHub に載らない。
// GitHub から取ったコードでビルドする共有 frontend では import 先が無く、
// `Module not found` でビルド全体が落ちていた（2026-09 に連続失敗）。
// 手元や専用プロジェクトのビルドでは sitemap.ts が実在するので、一覧は変わらない。
//
// 一覧の生成元は scripts/generate_sitemap_registry.py。書式はそちらに合わせる。
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FRONTEND = join(dirname(fileURLToPath(import.meta.url)), '..');
const ARTIFACTS = join(FRONTEND, 'src', 'app', 'artifacts');
const OUT = join(FRONTEND, 'src', 'lib', 'artifact-sitemaps.generated.ts');

function slugsWithSitemap() {
  if (!existsSync(ARTIFACTS)) return [];
  return readdirSync(ARTIFACTS)
    .filter((name) => !name.startsWith('[') && !name.startsWith('_'))
    .filter((name) => statSync(join(ARTIFACTS, name)).isDirectory())
    .filter((name) => existsSync(join(ARTIFACTS, name, 'sitemap.ts')))
    .sort();
}

function render(slugs) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate_sitemap_registry.py — do not edit.',
    '// 自前の sitemap.ts を持つ成果物の読み込み口。app/sitemap.ts が ARTIFACT_PAGES より優先して使う。',
    'import type { MetadataRoute } from "next";',
    '',
    'type SitemapModule = {',
    '  default: () => MetadataRoute.Sitemap | Promise<MetadataRoute.Sitemap>;',
    '};',
    '',
    'export const ARTIFACT_SITEMAPS: Record<string, () => Promise<SitemapModule>> = {',
    ...slugs.map((slug) => `  "${slug}": () => import("@/app/artifacts/${slug}/sitemap"),`),
    '};',
  ];
  return `${lines.join('\n')}\n`;
}

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
const listed = [...current.matchAll(/^\s*"([^"]+)": \(\) => import\(/gm)].map((m) => m[1]).sort();
const present = slugsWithSitemap();

if (listed.join('\n') === present.join('\n')) {
  console.log(`[sync-artifact-sitemaps] unchanged (${present.length} artifacts)`);
} else {
  writeFileSync(OUT, render(present), 'utf8');
  const dropped = listed.filter((slug) => !present.includes(slug));
  console.log(
    `[sync-artifact-sitemaps] ${present.length} artifacts` +
      (dropped.length ? `; dropped missing: ${dropped.join(', ')}` : ''),
  );
}
